"""
Task 1 HELOC — Weight of Evidence (WoE) preprocessing + ONE fully-connected DNN.

Evidence-based direction:
A published HELOC study reports that a neural network trained on WoE-encoded
features achieved AUC 81.40%, compared with 80.59% for its one-hot NN.
This script implements a leakage-safe, fold-local WoE pipeline using ONLY
the provided Task 1 CSV. It is a new candidate, not a guaranteed improvement.

Important safeguards:
- No Optuna search.
- No tree model, no ensemble, no external training data, no other neural net.
- Special values -7/-8/-9 and missing values are separate bins.
- Continuous feature bin edges are fit on the current training fold only.
- WoE maps for DNN training rows are generated by inner out-of-fold encoding
  so a row's own label is not used to encode that row.
- Validation/test rows are encoded using maps fit only on the outer training set.
- Existing task1.pt and task1_optuna.pt are never overwritten.

Run from project root:
python code\\task1_woe_dnn.py --mode train --csv data\\T1_data\\heloc_release.csv --device cpu --fit-final

Predict with the new checkpoint:
python code\\task1_woe_dnn.py --mode predict --csv path\\to\\unlabeled.csv --checkpoint task1_woe.pt --output task1_woe_predictions.csv
"""
from __future__ import annotations

import argparse
import json
import random
import re
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import torch
from sklearn.model_selection import StratifiedKFold
from torch import nn
from torch.utils.data import DataLoader, TensorDataset

import task1_optuna_cv as base


PROJECT_DIR = Path(__file__).resolve().parent.parent
SPECIAL_CODES = (-7, -8, -9)
DEFAULT_N_BINS = 6
DEFAULT_WOE_ALPHA = 10.0
DEFAULT_INNER_FOLDS = 5

# This compact architecture follows the small-MLP direction reported in the
# HELOC WoE paper, while remaining a single fully-connected DNN.
MODEL_PARAMS = {
    "hidden_dims": [16, 8, 4],
    "dropout": 0.05,
    "norm": "none",
    "activation": "relu",
    "lr": 0.001,
    "weight_decay": 0.01,
    "batch_size": 128,
    "ranking_weight": 0.0,
    "scaler": "none",  # WoE features are already on a comparable scale.
}

CATEGORICAL_ALIASES = {
    "maximum_illegal_trades_over_last_year",
    "maxdelq2publicreclast12m",
    "maximum_illegal_trades",
    "maxdelqever",
}


def set_seed(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def normalize_name(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", str(name).lower())


def is_categorical_feature(column: str) -> bool:
    return normalize_name(column) in CATEGORICAL_ALIASES


def read_numeric(frame: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    raw = frame[columns].apply(pd.to_numeric, errors="coerce")
    return raw.replace([np.inf, -np.inf], np.nan)


def load_training_data(csv_path: Path):
    if not csv_path.is_file():
        raise FileNotFoundError(f"Training CSV not found: {csv_path}")
    df = pd.read_csv(csv_path)
    if not {"sample_id", "is_at_risk"}.issubset(df.columns):
        raise ValueError("CSV must contain sample_id and is_at_risk.")
    columns = [c for c in df.columns if c not in ("sample_id", "is_at_risk")]
    if len(columns) != 23:
        raise ValueError(f"Expected 23 input features, found {len(columns)}.")
    y = pd.to_numeric(df["is_at_risk"], errors="raise").to_numpy(dtype=np.int64)
    if not np.isin(y, [0, 1]).all():
        raise ValueError("is_at_risk must contain only 0 and 1.")
    if df["sample_id"].duplicated().any():
        raise ValueError("sample_id contains duplicates.")
    return df, columns, y


def fit_binning(
    train_df: pd.DataFrame,
    feature_columns: list[str],
    n_bins: int,
) -> dict[str, Any]:
    """Fit feature-only bin definitions on the current training partition."""
    raw = read_numeric(train_df, feature_columns)
    specs: dict[str, Any] = {}

    for col in feature_columns:
        s = raw[col]
        valid = s[~s.isin(SPECIAL_CODES)].dropna()

        if is_categorical_feature(col):
            # The two MaxDelq fields are ordinal severity categories, not
            # ordinary continuous measurements.
            levels = sorted(float(v) for v in valid.unique())
            specs[col] = {
                "kind": "categorical",
                "levels": levels,
                "possible_bins": (
                    [f"cat_{v:g}" for v in levels]
                    + [f"special_{v}" for v in SPECIAL_CODES]
                    + ["missing", "unknown"]
                ),
            }
        else:
            if len(valid) == 0:
                edges: list[float] = []
            else:
                quantiles = np.linspace(0.0, 1.0, n_bins + 1)[1:-1]
                edges = sorted(
                    set(float(v) for v in np.quantile(valid.to_numpy(), quantiles))
                )
            n_valid_bins = len(edges) + 1
            specs[col] = {
                "kind": "continuous",
                "edges": edges,
                "possible_bins": (
                    [f"bin_{i}" for i in range(n_valid_bins)]
                    + [f"special_{v}" for v in SPECIAL_CODES]
                    + ["missing", "unknown"]
                ),
            }
    return {
        "feature_columns": list(feature_columns),
        "n_bins": int(n_bins),
        "features": specs,
    }


def value_to_bin(value: Any, spec: dict[str, Any]) -> str:
    if pd.isna(value):
        return "missing"
    try:
        x = float(value)
    except (TypeError, ValueError):
        return "unknown"

    if x in SPECIAL_CODES:
        return f"special_{int(x)}"

    if spec["kind"] == "categorical":
        levels = spec["levels"]
        # Exact integer-like category match.
        for level in levels:
            if x == level:
                return f"cat_{level:g}"
        return "unknown"

    edges = np.asarray(spec["edges"], dtype=np.float64)
    bin_index = int(np.searchsorted(edges, x, side="right"))
    return f"bin_{bin_index}"


def transform_to_bins(
    frame: pd.DataFrame,
    binning: dict[str, Any],
) -> np.ndarray:
    columns = binning["feature_columns"]
    missing = [c for c in columns if c not in frame.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")
    raw = read_numeric(frame, columns)

    encoded = np.empty((len(frame), len(columns)), dtype=object)
    for j, col in enumerate(columns):
        spec = binning["features"][col]
        encoded[:, j] = [
            value_to_bin(v, spec) for v in raw[col].to_numpy()
        ]
    return encoded


def fit_woe_maps(
    bin_ids: np.ndarray,
    y: np.ndarray,
    binning: dict[str, Any],
    alpha: float,
) -> list[dict[str, float]]:
    """Smoothed log(good distribution / bad distribution) per feature bin."""
    y = np.asarray(y, dtype=np.int64)
    total_good = int(np.sum(y == 0))
    total_bad = int(np.sum(y == 1))
    if total_good == 0 or total_bad == 0:
        raise ValueError("Both classes must be present to fit WoE maps.")

    maps: list[dict[str, float]] = []
    columns = binning["feature_columns"]

    for j, col in enumerate(columns):
        possible = list(binning["features"][col]["possible_bins"])
        k = max(1, len(possible))
        values = bin_ids[:, j]
        mapping: dict[str, float] = {}

        for category in possible:
            mask = values == category
            good_count = int(np.sum(mask & (y == 0)))
            bad_count = int(np.sum(mask & (y == 1)))

            good_dist = (good_count + alpha) / (total_good + alpha * k)
            bad_dist = (bad_count + alpha) / (total_bad + alpha * k)
            mapping[category] = float(np.log(good_dist / bad_dist))

        # Unknown category fallback is neutral evidence.
        mapping["unknown"] = mapping.get("unknown", 0.0)
        mapping["missing"] = mapping.get("missing", 0.0)
        maps.append(mapping)
    return maps


def apply_woe(
    bin_ids: np.ndarray,
    woe_maps: list[dict[str, float]],
) -> np.ndarray:
    x = np.zeros(bin_ids.shape, dtype=np.float32)
    for j, mapping in enumerate(woe_maps):
        x[:, j] = np.asarray(
            [mapping.get(str(v), 0.0) for v in bin_ids[:, j]],
            dtype=np.float32,
        )
    return x


def crossfit_training_woe(
    train_bin_ids: np.ndarray,
    y: np.ndarray,
    binning: dict[str, Any],
    alpha: float,
    inner_folds: int,
    seed: int,
) -> np.ndarray:
    """Create leakage-safe OOF WoE features for rows used to fit the DNN."""
    y = np.asarray(y, dtype=np.int64)
    class_counts = np.bincount(y, minlength=2)
    n_splits = min(int(inner_folds), int(class_counts.min()))
    if n_splits < 2:
        raise ValueError("Not enough samples per class for inner OOF WoE.")

    splitter = StratifiedKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=seed,
    )
    oof = np.zeros(train_bin_ids.shape, dtype=np.float32)

    for inner_train_idx, inner_valid_idx in splitter.split(train_bin_ids, y):
        maps = fit_woe_maps(
            train_bin_ids[inner_train_idx],
            y[inner_train_idx],
            binning,
            alpha,
        )
        oof[inner_valid_idx] = apply_woe(
            train_bin_ids[inner_valid_idx],
            maps,
        )
    return oof


def train_one_fold(
    train_df: pd.DataFrame,
    valid_df: pd.DataFrame,
    feature_columns: list[str],
    y_train: np.ndarray,
    y_valid: np.ndarray,
    seed: int,
    n_bins: int,
    alpha: float,
    inner_folds: int,
    max_epochs: int,
    patience: int,
    device: torch.device,
):
    set_seed(seed)

    # Bin boundaries use only outer-train feature values, not labels or
    # outer-validation values.
    binning = fit_binning(train_df, feature_columns, n_bins)
    train_bins = transform_to_bins(train_df, binning)
    valid_bins = transform_to_bins(valid_df, binning)

    # Each training row is encoded using mappings learned without that row.
    x_train = crossfit_training_woe(
        train_bins, y_train, binning, alpha, inner_folds, seed + 1000
    )
    # Outer validation is encoded using the full outer-training labels only.
    outer_maps = fit_woe_maps(train_bins, y_train, binning, alpha)
    x_valid = apply_woe(valid_bins, outer_maps)

    dataset = TensorDataset(
        torch.from_numpy(x_train),
        torch.from_numpy(y_train.astype(np.float32).reshape(-1, 1)),
    )
    loader = DataLoader(
        dataset,
        batch_size=int(MODEL_PARAMS["batch_size"]),
        shuffle=True,
        generator=torch.Generator().manual_seed(seed),
        drop_last=False,
    )

    model = base.make_model(x_train.shape[1], MODEL_PARAMS).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=float(MODEL_PARAMS["lr"]),
        weight_decay=float(MODEL_PARAMS["weight_decay"]),
    )
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="max", factor=0.5, patience=2, min_lr=1e-5
    )

    best_auc = -1.0
    best_epoch = 0
    stale = 0

    for epoch in range(1, max_epochs + 1):
        model.train()
        for batch_x, batch_y in loader:
            batch_x = batch_x.to(device)
            batch_y = batch_y.to(device)
            optimizer.zero_grad(set_to_none=True)
            logits = model(batch_x)
            loss = base.combined_loss(
                logits, batch_y, float(MODEL_PARAMS["ranking_weight"])
            )
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), max_norm=2.0)
            optimizer.step()

        auc = base.evaluate_auc(model, x_valid, y_valid, device)
        scheduler.step(auc)
        if auc > best_auc + 1e-4:
            best_auc = auc
            best_epoch = epoch
            stale = 0
        else:
            stale += 1
            if stale >= patience:
                break

    return float(best_auc), int(best_epoch)


def final_fit_woe(
    df: pd.DataFrame,
    feature_columns: list[str],
    y: np.ndarray,
    epochs: int,
    n_bins: int,
    alpha: float,
    inner_folds: int,
    seed: int,
    device: torch.device,
    checkpoint_path: Path,
):
    binning = fit_binning(df, feature_columns, n_bins)
    all_bins = transform_to_bins(df, binning)
    x_train = crossfit_training_woe(
        all_bins, y, binning, alpha, inner_folds, seed + 1000
    )
    full_maps = fit_woe_maps(all_bins, y, binning, alpha)

    dataset = TensorDataset(
        torch.from_numpy(x_train),
        torch.from_numpy(y.astype(np.float32).reshape(-1, 1)),
    )
    loader = DataLoader(
        dataset,
        batch_size=int(MODEL_PARAMS["batch_size"]),
        shuffle=True,
        generator=torch.Generator().manual_seed(seed),
        drop_last=False,
    )

    set_seed(seed)
    model = base.make_model(x_train.shape[1], MODEL_PARAMS).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=float(MODEL_PARAMS["lr"]),
        weight_decay=float(MODEL_PARAMS["weight_decay"]),
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=max(1, epochs), eta_min=1e-5
    )

    for epoch in range(1, epochs + 1):
        model.train()
        total_loss = 0.0
        seen = 0
        for batch_x, batch_y in loader:
            batch_x = batch_x.to(device)
            batch_y = batch_y.to(device)
            optimizer.zero_grad(set_to_none=True)
            logits = model(batch_x)
            loss = base.combined_loss(
                logits, batch_y, float(MODEL_PARAMS["ranking_weight"])
            )
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), max_norm=2.0)
            optimizer.step()
            total_loss += float(loss.item()) * len(batch_x)
            seen += len(batch_x)
        scheduler.step()
        print(
            f"Final fit epoch {epoch:02d}/{epochs} | "
            f"loss={total_loss / max(1, seen):.5f}",
            flush=True,
        )

    checkpoint = {
        "model_state_dict": model.state_dict(),
        "input_dim": int(x_train.shape[1]),
        "model_config": {
            "hidden_dims": list(MODEL_PARAMS["hidden_dims"]),
            "dropout": float(MODEL_PARAMS["dropout"]),
            "norm": MODEL_PARAMS["norm"],
            "activation": MODEL_PARAMS["activation"],
        },
        "training_config": MODEL_PARAMS,
        "binning": binning,
        "woe_maps": full_maps,
        "woe_alpha": float(alpha),
        "inner_folds": int(inner_folds),
        "final_epochs": int(epochs),
        "trained_on_all_rows": True,
        "train_rows": int(len(df)),
        "feature_encoding": "fold-local quantile binning + smoothed WoE",
    }
    checkpoint_path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(checkpoint, checkpoint_path)

    loaded = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    check_model = base.make_model(loaded["input_dim"], loaded["model_config"])
    check_model.load_state_dict(loaded["model_state_dict"], strict=True)
    check_model.eval()
    print(f"Saved checkpoint: {checkpoint_path}", flush=True)
    print("Checkpoint reload test: OK", flush=True)


def run_train(args):
    csv_path = Path(args.csv).expanduser().resolve()
    df, feature_columns, y = load_training_data(csv_path)
    device = base.choose_device(args.device)
    torch.set_num_threads(max(1, min(4, torch.get_num_threads())))

    raw = read_numeric(df, feature_columns)
    all_minus9 = raw.eq(-9).all(axis=1)
    any_special = raw.isin(SPECIAL_CODES).any(axis=1)

    print("=== TASK 1 WoE DNN ===", flush=True)
    print(f"Rows: {len(df)} | Original features: {len(feature_columns)}", flush=True)
    print(f"Device: {device}", flush=True)
    print(f"Rows with >=1 special code: {int(any_special.sum())}", flush=True)
    print(f"Rows with all 23 values = -9: {int(all_minus9.sum())}", flush=True)
    if all_minus9.any():
        print(
            "Positive rate among all--9 rows: "
            f"{float(y[all_minus9].mean()):.4f}",
            flush=True,
        )
    print(f"WoE bins per continuous feature: up to {args.n_bins}", flush=True)
    print(f"WoE smoothing alpha: {args.woe_alpha}", flush=True)
    print(f"Inner OOF folds: {args.inner_folds}", flush=True)
    print(f"One DNN architecture: {MODEL_PARAMS}", flush=True)
    print("No Optuna search; no ensemble; no external training data.", flush=True)

    df = df.copy()
    df["_target"] = y
    outer = StratifiedKFold(n_splits=3, shuffle=True, random_state=2026)

    fold_aucs = []
    fold_epochs = []
    for fold_no, (train_idx, valid_idx) in enumerate(outer.split(df, y), start=1):
        train_df = df.iloc[train_idx].reset_index(drop=True)
        valid_df = df.iloc[valid_idx].reset_index(drop=True)
        y_train = y[train_idx]
        y_valid = y[valid_idx]

        auc, best_epoch = train_one_fold(
            train_df=train_df,
            valid_df=valid_df,
            feature_columns=feature_columns,
            y_train=y_train,
            y_valid=y_valid,
            seed=2026 + fold_no,
            n_bins=args.n_bins,
            alpha=args.woe_alpha,
            inner_folds=args.inner_folds,
            max_epochs=args.max_epochs,
            patience=args.patience,
            device=device,
        )
        fold_aucs.append(auc)
        fold_epochs.append(best_epoch)
        print(
            f"Fold {fold_no}/3 | AUROC={auc:.6f} | best_epoch={best_epoch}",
            flush=True,
        )

    mean_auc = float(np.mean(fold_aucs))
    std_auc = float(np.std(fold_aucs, ddof=0))
    final_epochs = max(1, int(np.median(fold_epochs)))

    summary = {
        "experiment": "Task1 HELOC fold-local WoE + single DNN",
        "cv": "StratifiedKFold(3), shuffle=True, random_state=2026",
        "fold_seeds": [2027, 2028, 2029],
        "fold_auroc": fold_aucs,
        "mean_auroc": mean_auc,
        "std_auroc_population": std_auc,
        "fold_best_epochs": fold_epochs,
        "final_fit_epochs": final_epochs,
        "n_bins": int(args.n_bins),
        "woe_alpha": float(args.woe_alpha),
        "inner_folds": int(args.inner_folds),
        "model_config": MODEL_PARAMS,
        "note": (
            "Validation CV estimate only; not private-test performance. "
            "Binning and WoE maps are fit within each outer training fold. "
            "Training rows use inner OOF WoE encoding."
        ),
    }
    summary_path = Path(args.output_json).expanduser().resolve()
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print("\n=== WoE RESULT ===", flush=True)
    print(f"Mean 3-fold AUROC: {mean_auc:.5f} ± {std_auc:.5f}", flush=True)
    print(f"Fold AUROCs: {fold_aucs}", flush=True)
    print(f"Fold best epochs: {fold_epochs}", flush=True)
    print(f"Final fit epochs: {final_epochs}", flush=True)
    print(f"Saved summary: {summary_path}", flush=True)

    if args.fit_final:
        checkpoint_path = Path(args.checkpoint).expanduser().resolve()
        final_fit_woe(
            df=df,
            feature_columns=feature_columns,
            y=y,
            epochs=final_epochs,
            n_bins=args.n_bins,
            alpha=args.woe_alpha,
            inner_folds=args.inner_folds,
            seed=2026,
            device=device,
            checkpoint_path=checkpoint_path,
        )


def run_predict(args):
    checkpoint_path = Path(args.checkpoint).expanduser().resolve()
    csv_path = Path(args.csv).expanduser().resolve()
    output_path = Path(args.output).expanduser().resolve()

    checkpoint = torch.load(
        checkpoint_path, map_location="cpu", weights_only=True
    )
    frame = pd.read_csv(csv_path)
    bin_ids = transform_to_bins(frame, checkpoint["binning"])
    x = apply_woe(bin_ids, checkpoint["woe_maps"])

    model = base.make_model(
        checkpoint["input_dim"],
        checkpoint["model_config"],
    )
    model.load_state_dict(checkpoint["model_state_dict"], strict=True)
    model.eval()

    with torch.no_grad():
        logits = model(torch.from_numpy(x))
        probabilities = torch.sigmoid(logits).numpy().reshape(-1)

    result = pd.DataFrame({"is_at_risk_probability": probabilities})
    if "sample_id" in frame.columns:
        result.insert(0, "sample_id", frame["sample_id"].to_numpy())
    output_path.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(output_path, index=False)
    print(f"Saved {len(result)} predictions: {output_path}", flush=True)


